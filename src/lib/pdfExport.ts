import { jsPDF } from 'jspdf';
import { GeneratedQuestion, Syllabus } from '@/types';

export function exportQuestionsToPdf(
  questions: GeneratedQuestion[],
  syllabus: Syllabus,
  userRole: 'Teacher' | 'Student'
): void {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 16;
  const contentWidth = pageWidth - margin * 2;

  let y = 18;

  // Header Banner
  doc.setFillColor(30, 41, 59); // slate-800
  doc.rect(0, 0, pageWidth, 28, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(15);
  doc.text('AI Exam Question Predictor', margin, 12);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.text('Important Examination Questions (Syllabus-Grounded)', margin, 18);

  doc.setFontSize(8);
  doc.setTextColor(148, 163, 184); // slate-400
  const dateStr = new Date().toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'short',
    day: 'numeric'
  });
  doc.text(`Generated for: ${userRole} | ${dateStr}`, pageWidth - margin, 18, { align: 'right' });

  y = 36;

  // Subject Metadata Box
  doc.setFillColor(248, 250, 252);
  doc.setDrawColor(226, 232, 240);
  doc.roundedRect(margin, y, contentWidth, 20, 2, 2, 'FD');

  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.text(`${syllabus.subjectName} ${syllabus.subjectCode ? `(${syllabus.subjectCode})` : ''}`, margin + 4, y + 7);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(71, 85, 105);
  const deptText = `${syllabus.department || 'Academic Syllabus'} | ${syllabus.semester || 'Current Semester'} | Total Questions: ${questions.length}`;
  doc.text(deptText, margin + 4, y + 14);

  y += 26;

  // Render Each Question
  questions.forEach((q, index) => {
    // Check if new page needed
    if (y > pageHeight - 45) {
      doc.addPage();
      y = 18;
    }

    // Question Header Tag (e.g. Q1 | 10 Marks | Theory | Very High Importance)
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(9.5);
    doc.setTextColor(79, 70, 229); // indigo-600
    doc.text(`Question ${q.questionNumber}`, margin, y);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8.5);
    doc.setTextColor(100, 116, 139);
    const tagInfo = `[${q.marks} Marks] | [${q.questionType}] | [${q.difficulty} Difficulty] | Importance: ${q.predictedImportance} (${q.scorePercentage}%)`;
    doc.text(tagInfo, margin + 24, y);

    y += 5;

    // Question Prompt
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(9.5);
    doc.setTextColor(15, 23, 42);

    const questionLines = doc.splitTextToSize(q.questionText, contentWidth);
    doc.text(questionLines, margin, y);
    y += questionLines.length * 4.5 + 2;

    // Source Reference & Rationale
    doc.setFont('helvetica', 'italic');
    doc.setFontSize(8);
    doc.setTextColor(71, 85, 105);

    const sourceText = `Source: ${q.sourceSyllabusRef} -- Rationale: ${q.rationale}`;
    const sourceLines = doc.splitTextToSize(sourceText, contentWidth);
    doc.text(sourceLines, margin, y);
    y += sourceLines.length * 3.8 + 2;

    // Suggested Answer Outline if available
    if (q.suggestedAnswerOutline && q.suggestedAnswerOutline.length > 0) {
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(7.5);
      doc.setTextColor(13, 148, 136); // teal-600
      doc.text('Key Answering Points:', margin, y);
      y += 3.5;

      doc.setFont('helvetica', 'normal');
      doc.setTextColor(51, 65, 85);
      q.suggestedAnswerOutline.forEach((step) => {
        if (y > pageHeight - 15) {
          doc.addPage();
          y = 18;
        }
        const stepLines = doc.splitTextToSize(`* ${step}`, contentWidth - 4);
        doc.text(stepLines, margin + 4, y);
        y += stepLines.length * 3.4;
      });
      y += 1;
    }

    // Divider Line
    doc.setDrawColor(226, 232, 240);
    doc.line(margin, y, margin + contentWidth, y);
    y += 6;
  });

  // Footer Disclaimer on last page
  if (y > pageHeight - 20) {
    doc.addPage();
    y = 18;
  }
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7.5);
  doc.setTextColor(148, 163, 184);
  doc.text(
    'Notice: These questions are syllabus-grounded heuristic examination predictions generated by AI Exam Question Predictor.',
    margin,
    pageHeight - 8
  );

  // Trigger browser download
  const safeFilename = syllabus.subjectName.replace(/[^a-z0-9]/gi, '_').toLowerCase();
  doc.save(`${safeFilename}_important_exam_questions.pdf`);
}
